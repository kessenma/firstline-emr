// Single source of truth for which icon (and color family) represents each role.
//
// Icons are referenced by lucide *name* rather than by component, because web
// imports from `lucide-react` and mobile from `lucide-react-native` — the names
// are identical in both packages, the components are not. Each platform resolves
// the name through its own thin wrapper:
//   web:    apps/web/components/ui/RoleIcon.tsx
//   mobile: apps/mobile/src/components/ui/RoleIcon.tsx

import type { AccountType } from '../patient/enums';
import { roleColors } from './roles';

/** Lucide icon names used for roles. Present in both lucide-react and lucide-react-native. */
export type RoleIconName =
  | 'Stethoscope'
  | 'Users'
  | 'ShieldCheck'
  | 'HeartPulse'
  | 'ClipboardList'
  | 'Ambulance';

/**
 * Every value the UI themes as a role.
 *
 * 'Evac' is not in `AccountType` (nor in the `account_type` DB enum, which is
 * only Doctor/Triage) but a good deal of web UI still branches on it — the
 * medEvac button variants, StackedLoader, admin user creation. It is themed
 * here so those paths keep their red/medical treatment instead of silently
 * falling back to the neutral default.
 */
export type RoleKey = AccountType | 'Evac';

/** Key into `roleColors` — also the CSS token prefix on web (`--color-doctor-*`). */
export type RoleColorKey = keyof typeof roleColors;

export type RoleColorShade = keyof (typeof roleColors)['doctor'];

export interface RoleTheme {
  icon: RoleIconName;
  /** Short label for UI chips/cards. For the formal name use ACCOUNT_TYPE_LABELS. */
  label: string;
  description: string;
  colorKey: RoleColorKey;
}

export const roleThemes: Record<RoleKey, RoleTheme> = {
  Doctor: {
    icon: 'Stethoscope',
    label: 'Doctor',
    description: 'Medical consultation and diagnosis',
    colorKey: 'doctor',
  },
  Triage: {
    icon: 'Users',
    label: 'Triage',
    description: 'Patient intake and prioritization',
    colorKey: 'triage',
  },
  Admin: {
    icon: 'ShieldCheck',
    label: 'Admin',
    description: 'System administration and user management',
    colorKey: 'navy',
  },
  Nurse: {
    icon: 'HeartPulse',
    label: 'Nurse',
    description: 'Patient care and vitals',
    colorKey: 'medical',
  },
  Coordinator: {
    icon: 'ClipboardList',
    label: 'Coordinator',
    description: 'Care coordination and scheduling',
    colorKey: 'navy',
  },
  Evac: {
    icon: 'Ambulance',
    label: 'Evacuation',
    description: 'Emergency evacuation coordination',
    colorKey: 'medical',
  },
};

/** Used when a user has no account type set, or an unrecognized one. */
export const DEFAULT_ROLE_THEME: RoleTheme = {
  icon: 'Users',
  label: 'Staff',
  description: 'Fajr MedFlow user',
  colorKey: 'navy',
};

export function getRoleTheme(accountType?: string | null): RoleTheme {
  if (accountType && accountType in roleThemes) {
    return roleThemes[accountType as RoleKey];
  }
  return DEFAULT_ROLE_THEME;
}

export function getRoleIconName(accountType?: string | null): RoleIconName {
  return getRoleTheme(accountType).icon;
}

export function getRoleColorSet(
  accountType?: string | null,
): (typeof roleColors)[RoleColorKey] {
  return roleColors[getRoleTheme(accountType).colorKey];
}

/** Hex value for a role — use on mobile (RN styles take literal colors). */
export function getRoleColor(
  accountType?: string | null,
  shade: RoleColorShade = 'primary',
): string {
  return getRoleColorSet(accountType)[shade];
}

/**
 * CSS variable reference for a role — use on web, e.g. `var(--color-doctor-primary)`.
 * Tokens are generated by `pnpm --filter @fajr/shared generate:css`.
 */
export function getRoleCssVar(
  accountType?: string | null,
  shade: RoleColorShade = 'primary',
): string {
  return `var(--color-${getRoleTheme(accountType).colorKey}-${shade})`;
}
